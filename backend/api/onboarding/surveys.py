"""Опросы из ТЗ (3.5, 4.1–4.3).

Сигнал HR (ТЗ): самый негативный вариант — последний в списке; «Да» на вопрос о том,
о чём не сказали заранее; «Нет» на вопрос о встрече с руководителем; «Не уверен(а)»
или «Нет» на вопрос о продолжении работы. Вопрос «что было самым сложным» сигнала не даёт.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Question:
    text: str
    options: tuple[str, ...] = ()       # пусто — свободный ответ сообщением
    signal: frozenset[int] = frozenset()  # индексы вариантов, которые шлют сигнал HR
    follow_up: int | None = None        # вариант, после которого просим написать одним сообщением


@dataclass(frozen=True)
class Survey:
    kind: str
    title: str
    questions: tuple[Question, ...]


