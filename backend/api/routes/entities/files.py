async def convert_doc_to_pdf(doc_path: Path) -> Optional[Path]:
    """
    Convert DOC/DOCX/ODT/RTF to PDF using LibreOffice.
    Returns path to generated PDF or None on failure.
    LibreOffice is installed in Docker (libreoffice-writer-nogui).
    """
    try:
        # Create a temp dir for LibreOffice output
        with tempfile.TemporaryDirectory() as tmp_dir:
            # Run LibreOffice headless conversion
            cmd = [
                'libreoffice', '--headless', '--convert-to', 'pdf',
                '--outdir', tmp_dir,
                str(doc_path)
            ]
            file_logger.info(f"DOC_TO_PDF: running {' '.join(cmd)}")

            proc = await asyncio.create_subprocess_exec(
                *cmd,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, stderr = await asyncio.wait_for(proc.communicate(), timeout=120)

            if proc.returncode != 0:
                file_logger.error(
                    f"DOC_TO_PDF: LibreOffice failed (rc={proc.returncode}): "
                    f"stderr={stderr.decode('utf-8', errors='replace')}"
                )
                return None

            # Find the generated PDF
            pdf_files = list(Path(tmp_dir).glob('*.pdf'))
            if not pdf_files:
                file_logger.error("DOC_TO_PDF: no PDF generated by LibreOffice")
                return None

            # Move PDF to same directory as original doc
            src_pdf = pdf_files[0]
            dst_pdf = doc_path.with_suffix('.pdf')
            shutil.copy2(str(src_pdf), str(dst_pdf))

            file_logger.info(f"DOC_TO_PDF: success → {dst_pdf} ({dst_pdf.stat().st_size} bytes)")
            return dst_pdf

    except asyncio.TimeoutError:
        file_logger.error("DOC_TO_PDF: LibreOffice timed out (120s)")
        return None
    except Exception as e:
        file_logger.error(f"DOC_TO_PDF: unexpected error: {e}")
        return None


async def convert_pdf_to_images(
    pdf_path: Path,
    entity_id: int,
    org_id: int,
    uploaded_by: int,
    db: AsyncSession,
) -> list:
    """
    Convert each page of a PDF file to a JPEG image and save as entity files.
    Returns list of created EntityFile records.
    """
    created_files = []
    entity_files_dir = ENTITY_FILES_DIR / str(entity_id)
    entity_files_dir.mkdir(parents=True, exist_ok=True)

    try:
        pdf_bytes = pdf_path.read_bytes()
        doc = fitz.open(stream=pdf_bytes, filetype="pdf")

        for page_num in range(len(doc)):
            page = doc[page_num]
            # Render page to pixmap at specified DPI
            zoom = PDF_RENDER_DPI / 72  # 72 is default PDF DPI
            mat = fitz.Matrix(zoom, zoom)
            pix = page.get_pixmap(matrix=mat)

            # Convert to JPEG bytes
            img_bytes = pix.tobytes(output="jpeg")
            img_size = len(img_bytes)

            # Also save to disk (optional, for backward compat)
            img_name = f"cv_page_{page_num + 1}_{uuid.uuid4().hex[:8]}.jpg"
            img_path = entity_files_dir / img_name
            try:
                img_path.write_bytes(img_bytes)
            except Exception:
                pass  # Disk save is optional, DB is primary

            # Create DB record with file content
            img_file = EntityFile(
                entity_id=entity_id,
                org_id=org_id,
                file_type=EntityFileType.resume,
                file_name=f"Резюме стр. {page_num + 1}.jpg",
                file_path=str(img_path),
                file_size=img_size,
                mime_type="image/jpeg",
                description=f"Автоконвертация из PDF (стр. {page_num + 1})",
                uploaded_by=uploaded_by,
                file_data=img_bytes,
            )
            db.add(img_file)
            created_files.append(img_file)

            file_logger.info(
                f"PDF_TO_IMAGE: page {page_num + 1}/{len(doc)} | entity_id={entity_id} | "
                f"size={img_size} bytes | path={img_path}"
            )

        doc.close()
        await db.commit()

    except Exception as e:
        file_logger.error(f"PDF_TO_IMAGE failed for entity {entity_id}: {e}")
        # Don't crash — PDF was already saved, images are a bonus

    return created_files


def extract_photo_from_pdf(pdf_bytes: bytes):
    """Best-effort: вытащить фото кандидата, встроенное в PDF-резюме.

    Возвращает (image_bytes, ext) или None. Эвристика: портретное/квадратное
    встроенное растровое изображение на первых страницах, не иконка и не фон на
    всю страницу/скан. Нужно, чтобы аватаром было ФОТО человека (если в PDF оно
    есть), а не рендер страницы резюме (страницы сохраняются как
    file_type=resume и в аватар не идут — см. candidate_search.photo_file_map).
    """
    try:
        doc = fitz.open(stream=pdf_bytes, filetype="pdf")
    except Exception:
        return None
    best_score = -1.0
    best = None
    try:
        for pno in range(min(2, doc.page_count)):
            page = doc[pno]
            page_area = max(1.0, page.rect.width * page.rect.height)
            for img in page.get_images(full=True):
                xref = img[0]
                try:
                    base = doc.extract_image(xref)
                except Exception:
                    continue
                w = base.get("width") or 0
                h = base.get("height") or 0
                if w < 80 or h < 80:
                    continue  # иконка / декор
                ar = h / w
                if ar < 0.85 or ar > 2.4:
                    continue  # широкий логотип / баннер — берём портрет/квадрат
                try:
                    rects = page.get_image_rects(xref)
                    coverage = (max((r.width * r.height for r in rects), default=0.0)
                                / page_area)
                except Exception:
                    coverage = 0.0
                if coverage > 0.55:
                    continue  # фон на всю страницу / скан страницы
                # фото обычно — самое крупное портретное изображение; приоритет 1-й стр.
                score = coverage + (0.5 if pno == 0 else 0.0)
                if score > best_score:
                    best_score = score
                    best = (base["image"], (base.get("ext") or "png").lower())
    except Exception:
        return None
    finally:
        try:
            doc.close()
        except Exception:
            pass
    return best


