import { describe, it, expect } from "vitest";
import { pluralRu } from "../plural";

describe("pluralRu", () => {
  const v = (n: number) => `${n} ${pluralRu(n, "вакансия", "вакансии", "вакансий")}`;
  it("1 / 2–4 / 5+ и 11–14", () => {
    expect([1, 2, 4, 5, 11, 12, 14, 21, 22, 25, 101].map(v)).toEqual([
      "1 вакансия", "2 вакансии", "4 вакансии", "5 вакансий", "11 вакансий", "12 вакансий",
      "14 вакансий", "21 вакансия", "22 вакансии", "25 вакансий", "101 вакансия",
    ]);
  });
});
